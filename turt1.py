import turtle
win=turtle.getscreen()
t=turtle.Turtle()
t.forward(100)
t.right(90)
t.backward(100)
t.left(90)
t.bk(100)
t.rt(90)
t.fd(100)
t.goto(100,100)
t.setpos(-100,-100)
t.penup()
t.fd(100)
t.pendown()
t.rt(45)
t.fd(100)
win.clear()
t.setpos(0,0)
t.dot(10)
for i in range(10,100,10):
	t.circle(i)

win.mainloop()
